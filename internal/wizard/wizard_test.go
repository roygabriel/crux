func TestRenderSummary(t *testing.T) {
	t.Parallel()

	cfg := config.DefaultConfig()
	cfg.Project.Name = "test-project"
	cfg.Agents = map[string]config.AgentConfig{
		"eng-1": {
			Plugin:     "claude",
			Role:       "engineer",
			Permission: "standard",
		},
	}

	summary := RenderSummary(cfg)

	if !strings.HasPrefix(summary, "# Generated by crux init") {
		t.Error("RenderSummary() missing header comment")
	}

	for _, want := range []string{"test-project", "claude", "engineer", "standard"} {
		if !strings.Contains(summary, want) {
			t.Errorf("RenderSummary() missing expected content %q", want)
		}
	}
}

