func TestToPluginHuhOptions(t *testing.T) {
	t.Parallel()

	opts := toPluginHuhOptions()
	if got := len(opts); got != len(pluginOptions) {
		t.Fatalf("toPluginHuhOptions() returned %d options, want %d", got, len(pluginOptions))
	}
	for i, opt := range opts {
		if opt.Value != pluginOptions[i].Value {
			t.Errorf("option[%d].Value = %q, want %q", i, opt.Value, pluginOptions[i].Value)
		}
	}
}

